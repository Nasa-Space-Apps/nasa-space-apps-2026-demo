// Portrait of the "Created by" card, step 2: the masks of build.py -> smooth vector paths (potrace) -> src/lib/portraits/<id>.ts
//   npm i --no-save potrace
//   node scripts/portrait/trace.mjs <workdir> <person-id>
// The 800x1000 work canvas is cut to the square x 0..800, y VY..VY+800 and scaled to the 400x400 box of components/Portrait.tsx.
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const potrace = require("potrace");
const [dir, id] = process.argv.slice(2);
if (!dir || !id) throw new Error("usage: node scripts/portrait/trace.mjs <workdir> <person-id>");
const VY = 60;
const K = 0.5;

const trace = (file) =>
  new Promise((ok, no) => {
    const t = new potrace.Potrace({ turdSize: 25, optTolerance: 0.6, alphaMax: 1.1, threshold: 128 });
    t.loadImage(file, (e) => (e ? no(e) : ok(t.getPathTag())));
  });
const fmt = (n) => String(Math.round(n * 10) / 10);

const layers = [];
for (const [name, tone] of JSON.parse(fs.readFileSync(`${dir}/layers.json`, "utf8"))) {
  const d = /d="([^"]*)"/.exec(await trace(`${dir}/masks/${name}.png`))[1];
  let i = 0; // potrace only emits absolute M / L / C: numbers alternate x, y
  const out = d
    .replace(/-?\d+(\.\d+)?/g, (m) => fmt(i++ % 2 === 0 ? +m * K : (+m - VY) * K))
    .replace(/\s*,\s*/g, " ")
    .replace(/\s+/g, " ")
    .replace(/ ?([MLCZ]) ?/g, "$1")
    .trim();
  if (out) layers.push([name, tone, out]);
}

const file = path.join(path.dirname(fileURLToPath(import.meta.url)), `../../src/lib/portraits/${id}.ts`);
fs.writeFileSync(
  file,
  `// GENERATED by scripts/portrait (build.py + trace.mjs) from a photo: do not edit by hand. Layers are painted back to front.\n` +
    `import type { PortraitLayer } from "../themes";\n\n` +
    `const layers: PortraitLayer[] = [\n${layers.map(([n, t, d]) => `  // ${n}\n  ["${t}", "${d}"],`).join("\n")}\n];\n\nexport default layers;\n`,
);
console.log(`${layers.length} layers, ${layers.reduce((a, l) => a + l[2].length, 0)} chars -> ${file}`);
