/**
 * Story checkpoints: points of interest on the terrain that open an info card (and play a narration) when the vehicle reaches them. They are built from
 * the beats of a mission's story (lib/story.ts, `beatToCheckpoint`).
 * The list of a mission, in order, is also its ROUTE: the first one is where the vehicle starts, the last one is where it ends,
 * and the vehicle always travels the path between consecutive checkpoints (see lib/route.ts).
 */
export type Checkpoint = {
  id: string;
  name: string; // card title
  place: string; // small line under the title (date / location)
  x: number; // world coordinates (terrain is centred on 0,0; z grows towards the camera)
  z: number;
  via?: [x: number, z: number][]; // waypoints on the way FROM the previous checkpoint TO this one (keeps the route off steep ground)
  image: string; // illustration of the beat (public/models/<mission>/images/<id>.jpg)
  credit: string; // image credit, shown under the picture
  text: string; // short written summary shown on the card
  narration: string; // spoken script (story voice). Changing it requires `npm run story-audio -- <mission>` to re-record the clip
  audio: string; // pre-recorded narration (public/models/<mission>/audio/<id>.mp3, generated by scripts/generate-story-audio.mjs)
  facts: [label: string, value: string][]; // up to 3
  imageRatio?: string; // CSS aspect-ratio of `image` (default "16 / 10"; the story illustrations are "4 / 5")
  sources?: { type: string; host: string; url: string }[]; // where the facts come from, as links
};
