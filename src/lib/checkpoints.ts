/**
 * Story checkpoints: points of interest on the terrain that open an info card (and play a narration) when the rover reaches them.
 * The list of a mission, in order, is also its ROUTE: the first one is where the vehicle starts, the last one is where it ends,
 * and the vehicle always travels the path between consecutive checkpoints (see lib/route.ts).
 */
export type Checkpoint = {
  id: string;
  name: string; // card title
  place: string; // small line under the title (date / location)
  x: number; // world coordinates (terrain is centred on 0,0; z grows towards the camera)
  z: number;
  via?: [x: number, z: number][]; // waypoints on the way FROM the previous checkpoint TO this one (keeps the route off steep ground)
  image: string; // /images/checkpoints/*.jpg, 16:10
  credit: string; // image credit, shown under the picture
  text: string; // short written summary shown on the card
  narration: string; // spoken script (story voice). Changing it requires `npm run narration` to re-record the audio
  audio: string; // pre-recorded narration (public/narration/<id>.mp3, generated by scripts/generate-narration.mjs)
  facts: [label: string, value: string][]; // up to 3
  imageRatio?: string; // CSS aspect-ratio of `image` (default "16 / 10"; the Opportunity story's illustrations are "4 / 5")
  source?: { label: string; url: string }; // where the facts come from (the Opportunity story)
  noGuide?: boolean; // the voice guide stays silent about this checkpoint (no per-checkpoint guide lines were recorded for it)
  demo?: boolean; // fictional demo checkpoint (lib/checkpoints-demo.ts): its `audio` is borrowed from another checkpoint and the voice guide stays silent about it
};

