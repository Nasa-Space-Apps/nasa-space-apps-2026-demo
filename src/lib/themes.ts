/**
 * The one theme of the demo: "Primer" (reference: primer.io/payment-pioneers). Warm off-white canvas, near-black ink, light grey surfaces, a single
 * orange accent, a tight grotesque for text and a mono for labels. Flat: no shadows, no gradients. See docs/design.md.
 *
 * This object is the single source of truth: `app/layout.tsx` publishes it as CSS variables (`cssVars`) for `globals.css`, and canvas / WebGL code
 * (minimap, globe) reads it directly.
 */

export type Theme = {
  id: string;
  name: string;
  font: string; // text
  mono: string; // labels, buttons, numbers
  canvas: string; // page background
  surface: string; // cards and panels
  ink: string; // main text and primary buttons
  inkSoft: string; // primary button hover
  muted: string; // secondary text
  line: string; // hairlines and dividers
  accent: string; // the main colour: current position, route, pins
  accentInk: string; // text on the accent
  accentSoft: string; // links on hover (reference: primer.io)
  hover: string; // fill that sweeps across a button on hover (reference: primer.io)
  radius: number; // panels
  radiusSm: number; // buttons and chips
  ease: string; // every transition uses this curve
  dur: { fast: number; base: number; slow: number }; // ms
  /** Minimap: topographic contours. */
  map: { bg: string; minor: string; major: string; minorW: number; majorW: number; every: number };
  trail: { color: string; width: number; dash: number[] };
  marker: { dot: string; ring: string; arrow: string };
  checkpoint: { pin: string; done: string; ring: string }; // minimap squares: pending fill / reached fill / outline
  /** 3D beacons of the checkpoints in the scene. */
  beacon: { pending: string; active: string; done: string };
  /** Flat portraits of the "Created by" card (components/Portrait.tsx): one blue family in a few tones over a light grey square. */
  portrait: { bg: string; skin: string; skinShade: string; skinDeep: string; skinLight: string; eye: string; deep: string; hairLight: string; jacket: string; jacketLight: string; shirt: string };
  /** Wireframe globe view. */
  globe: { bg: string; line: string; star: string; ink: string; tag: string; tagText: string; pin: string };
};

/** One flat shape of a portrait: its tone and its SVG path on a 400×400 grid (lib/portraits/<id>.ts, generated by scripts/portrait). */
export type PortraitLayer = [tone: keyof Theme["portrait"], d: string];

